"""Reads ledger_*.csv (from energy_ledger.py) and writes ledger_tables.md. Read-only otherwise."""

import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent


def rd(name):
    with (HERE / name).open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


led = rd("ledger_runs.csv")
spr = rd("ledger_controller_spread.csv")
idl = rd("ledger_ideal.csv")
fl = lambda r, k: float(r[k])  # noqa: E731
out = []
P = out.append

lines = ["E_wheel_net_Wh_DERIV", "E_rr_Wh_MEAS", "E_aero_Wh_MEAS", "E_fb_Wh_MEAS", "E_gear_Wh_MEAS",
         "E_visc_Wh_MEAS", "E_mi_Wh_MEAS", "E_R0_Wh_MEAS", "E_R1_Wh_MEAS", "dEC1_Wh_DERIV", "dKE_eff_Wh_DERIV"]

P("# Ledger tables (generated by summarise_ledger.py from ledger_runs.csv)\n")
P("## 1. Share of net battery chemical energy, controller F\n")
P("Net E = rr + aero + friction-brake + gear + viscous + motor/inverter + R0 + R1 + dEC1 + dKE (exact identity).\n")
P("| Cycle | Case | SoH | E [Wh] | rr % | aero % | fric.brake % | gear % | visc % | motor/inv % | R0 % | R1 % | dEC1+dKE % | regen terminal Wh | E+ Wh | E- Wh |")
P("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in led:
    if r["controller"] != "F" or (r["case"], r["soh"]) not in {("B0", "1.0"), ("B0", "0.7"), ("BCS", "0.7")}:
        continue
    E = fl(r, "E_chem_Wh_MEAS")
    pc = lambda k: 100 * fl(r, k) / E  # noqa: E731
    P(f"| {r['cycle']} | {r['case']} | {r['soh']} | {E:.1f} | {pc('E_rr_Wh_MEAS'):.1f} | {pc('E_aero_Wh_MEAS'):.1f} | "
      f"{pc('E_fb_Wh_MEAS'):.1f} | {pc('E_gear_Wh_MEAS'):.1f} | {pc('E_visc_Wh_MEAS'):.2f} | {pc('E_mi_Wh_MEAS'):.1f} | "
      f"{pc('E_R0_Wh_MEAS'):.2f} | {pc('E_R1_Wh_MEAS'):.3f} | {pc('dEC1_Wh_DERIV') + pc('dKE_eff_Wh_DERIV'):.3f} | "
      f"{fl(r, 'regen_terminal_Wh_MEAS'):.1f} | {fl(r, 'E_pos_Wh_MEAS'):.1f} | {fl(r, 'E_neg_Wh_MEAS'):.1f} |")

P("\n## 2. Largest controller spread (F vs S vs F01) per ledger line, as % of E_chem(F)\n")
P("Maximum over all cycle x case x SoH groups of (max - min over the three controllers).\n")
P("| Ledger line | max spread [Wh] | max spread [% of E_chem(F)] | group where it occurs |")
P("|---|---|---|---|")
for k in spr[0]:
    if "_range_Wh_" not in k:
        continue
    best = max(spr, key=lambda r: abs(float(r[k])) / float(r["E_chem_F_Wh"]))
    P(f"| {k.replace('_range', '')} | {float(best[k]):.3f} | {100 * float(best[k]) / float(best['E_chem_F_Wh']):.3f} | {best['cycle']}/{best['case']}/SoH {best['soh']} |")
for k, unit in (("rmse_range_ms", "m/s"), ("shortfall_range_pp", "pp")):
    best = max(spr, key=lambda r: abs(float(r[k])))
    P(f"| {k} | {float(best[k]):.4f} {unit} | - | {best['cycle']}/{best['case']}/SoH {best['soh']} |")

P("\n## 3. Same-cycle spread restricted to complete, in-capability scenarios (class A: B0, S1/S2/UDDS)\n")
P("| Cycle | SoH | E_F | E_S | E_F01 | spread % of E_F | RMSE F / S / F01 [m/s] | ideal-tracking Wh/km (k_r0 0.5) | F - ideal [Wh/km] | % |")
P("|---|---|---|---|---|---|---|---|---|---|")
idx = {(r["cycle"], r["k_r0"], r["soh"]): r for r in idl if float(r["stretch"]) == 1.0}
for cyc in ("S1", "S2", "UDDS"):
    for soh in ("1.0", "0.7"):
        rs = {r["controller"]: r for r in led if r["cycle"] == cyc and r["case"] == "B0" and r["soh"] == soh}
        e = {c: fl(rs[c], "E_chem_Wh_MEAS") / fl(rs[c], "distance_km") for c in rs}
        spread = 100 * (max(e.values()) - min(e.values())) / e["F"]
        i = idx.get((cyc, "0.5", soh))
        if i and i["feasible"] == "True":
            gap = e["F"] - float(i["Wh_per_km"])
            ideal_s, gap_s, pct = f"{float(i['Wh_per_km']):.3f}", f"{gap:+.3f}", f"{100 * gap / e['F']:+.2f}"
        else:
            ideal_s, gap_s, pct = "infeasible (reference exceeds motor limit)", "-", "-"
        P(f"| {cyc} | {soh} | {e['F']:.3f} | {e['S']:.3f} | {e['F01']:.3f} | {spread:.3f} | "
          f"{fl(rs['F'], 'rmse_ms'):.3f} / {fl(rs['S'], 'rmse_ms'):.3f} / {fl(rs['F01'], 'rmse_ms'):.3f} | {ideal_s} | {gap_s} | {pct} |")

P("\n## 4. What SoH alone does at exact tracking (ideal, class A plant)\n")
P("| Cycle | k_r0 | E(SoH 1.0) Wh/km | E(SoH 0.7) Wh/km | change % | R0 loss share SoH1.0 % | R0 loss SoH0.7 % |")
P("|---|---|---|---|---|---|---|")
for cyc in ("S1", "S2"):
    for k in ("0.5", "2.0"):
        a, b = idx[(cyc, k, "1.0")], idx[(cyc, k, "0.7")]
        ea, eb = float(a["E_chem_Wh"]), float(b["E_chem_Wh"])
        P(f"| {cyc} | {k} | {float(a['Wh_per_km']):.3f} | {float(b['Wh_per_km']):.3f} | {100 * (eb - ea) / ea:+.3f} | "
          f"{100 * float(a['E_R0_Wh']) / ea:.2f} | {100 * float(b['E_R0_Wh']) / eb:.2f} |")

P("\n## 5. Friction braking forced by the charge limit at exact tracking (IDEAL floor) vs measured (controller F)\n")
P("Floor ignores torque lag and discharge-side shortfall; it is not meaningful where the cycle is not completed (US06, incomplete UDDS).\n")
P("| Cycle | Case | SoH | floor [Wh] | measured F [Wh] | measured - floor [Wh] | as % of E_chem(F) | floor / measured |")
P("|---|---|---|---|---|---|---|---|")
efb = {(r["cycle"], r["case"], r["soh"]): fl(r, "E_chem_Wh_MEAS") for r in led if r["controller"] == "F"}
for r in rd("ledger_friction_floor.csv"):
    if r["case"] == "B0" or r["soh"] not in ("1.0", "0.7") or float(r["measured_fb_F_Wh"]) == 0 and float(r["floor_fb_Wh"]) == 0:
        continue
    fb, ms = float(r["floor_fb_Wh"]), float(r["measured_fb_F_Wh"])
    P(f"| {r['cycle']} | {r['case']} | {r['soh']} | {fb:.2f} | {ms:.2f} | {ms - fb:+.2f} | {100 * (ms - fb) / efb[(r['cycle'], r['case'], r['soh'])]:+.2f} | {fb / ms:.2f} |")

P("\n## 6. Leverage of the speed reference (IDEAL, exact tracking of a uniformly slowed reference, same distance)\n")
P("k_r0 = 0.5. Duration grows by the stretch factor. This is a different task (longer trip), not a controller gain.\n")
P("| Cycle | stretch | SoH | duration [s] | Wh/km | change vs unstretched ideal % |")
P("|---|---|---|---|---|---|")
for r in idl:
    if r.get("stretch", "1.0") == "1.0" or r["feasible"] != "True":
        continue
    b = idx.get((r["cycle"], "0.5", r["soh"]))
    ref = float(b["Wh_per_km"]) if b and b["feasible"] == "True" else None
    ch = f"{100 * (float(r['Wh_per_km']) - ref) / ref:+.2f}" if ref else "n/a (unstretched infeasible)"
    P(f"| {r['cycle']} | {r['stretch']} | {r['soh']} | {float(r['duration_s']):.0f} | {float(r['Wh_per_km']):.3f} | {ch} |")

(HERE / "ledger_tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))
