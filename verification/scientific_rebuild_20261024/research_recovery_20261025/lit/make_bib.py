"""Write ../references.bib from ../related_work_matrix.csv; full author lists from raw/abstracts.json where present.
Every entry carries the access label in `note`. Non-DOI items (retailer listings) are @misc."""

import csv
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RR = HERE.parent
oa = json.loads((HERE / "raw" / "abstracts.json").read_text(encoding="utf-8"))
with (RR / "related_work_matrix.csv").open(encoding="utf-8") as f:
    rows = list(csv.DictReader(f))


def esc(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


out = ["% references.bib - generated by lit/make_bib.py from related_work_matrix.csv (2026-10-25).",
       "% 'note' gives the access level: FT full text read, AB abstract read, MD metadata only, SEC secondary summary.", ""]
for r in rows:
    doi = r["doi"] if r["doi"] not in ("", "none") else ""
    rec = oa.get(doi, {})
    authors = " and ".join(rec["authors"]) if rec.get("authors") else r["authors"].replace(", ", " and ").replace(" et al.", " and others")
    venue = r["venue"]
    conf = re.search(r"\b(CCTA|CDC|VPPC|ITEC|DSCC|Conference|IECON|Proc\.)", venue)
    if not doi:
        typ, vfield = "misc", f"  howpublished = {{{esc(venue)}}},"
    elif "thesis" in venue.lower():
        typ, vfield = "mastersthesis", "  school = {West Virginia University},"
    elif "arXiv" in venue:
        typ, vfield = "misc", "  howpublished = {arXiv preprint},"
    elif conf:
        typ, vfield = "inproceedings", f"  booktitle = {{{esc(venue)}}},"
    else:
        typ, vfield = "article", f"  journal = {{{esc(venue)}}},"
    out += [f"@{typ}{{{r['id']},", f"  title = {{{{{esc(r['title'])}}}}},", f"  author = {{{esc(authors)}}},",
            f"  year = {{{r['year']}}},", vfield]
    if doi:
        out.append(f"  doi = {{{doi}}},")
    out += [f"  url = {{{r['url']}}},", f"  note = {{Access: {esc(r['access'])}. Matrix category: {esc(r['category'])}}}", "}", ""]
(RR / "references.bib").write_text("\n".join(out), encoding="utf-8")
print(len(rows), "entries written")
