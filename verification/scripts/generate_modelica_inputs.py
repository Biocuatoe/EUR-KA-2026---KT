"""Generate Modelica inputs from the project's configuration files.

Reads configs/parameters.yaml and configs/cycles/profiles.yaml (data only). Does not import eureka and does
not read any Python plant output. Writes:
  verification/modelica/EurekaPlant/Parameters.mo
  verification/modelica/EurekaPlant/Profiles.mo
  verification/modelica/generated_inputs.json   (source file hashes and the values written)
"""
import hashlib
import json
import pathlib
import sys

import yaml

root = pathlib.Path(sys.argv[1])
pkg = root / "verification/modelica/EurekaPlant"
pkg.mkdir(parents=True, exist_ok=True)
sha = lambda p: hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()

UNIT = {"kg": "kg", "m^2": "m2", "dimensionless": "1", "m": "m", "kg/m^3": "kg/m3", "m/s^2": "m/s2", "kg*m^2": "kg.m2",
        "N*m*s": "N.m.s", "N*m": "N.m", "W": "W", "s": "s", "V": "V", "A*h": "A.h", "ohm": "Ohm", "F": "F", "m/s": "m/s"}
# (yaml group, yaml key, modelica name)
WANT = [("vehicle", "mass", "M"), ("vehicle", "frontal_area", "A_f"), ("vehicle", "drag_coefficient", "C_d"),
        ("vehicle", "rolling_resistance", "C_rr"), ("vehicle", "wheel_radius", "r_w"), ("vehicle", "air_density", "rho"),
        ("vehicle", "gravity", "g"), ("drivetrain", "gear_ratio", "G"), ("drivetrain", "gear_efficiency", "eta_g"),
        ("drivetrain", "motor_inertia", "J_m"), ("drivetrain", "motor_viscous_friction", "B_m"),
        ("drivetrain", "motor_inverter_efficiency", "eta_mi"), ("drivetrain", "torque_max", "T_max"),
        ("drivetrain", "power_max", "P_max"), ("drivetrain", "torque_time_constant", "tau_T"),
        ("battery", "open_circuit_voltage", "V_oc"), ("battery", "capacity", "Q_Ah"), ("battery", "r0_new", "R0_new"),
        ("battery", "r1_new", "R1_new"), ("battery", "c1", "C1"), ("battery", "k_r0", "k_r0"), ("battery", "k_r1", "k_r1"),
        ("simulation", "speed_smoothing", "v_eps")]

pfile = root / "configs/parameters.yaml"
cfg = yaml.safe_load(pfile.read_text(encoding="utf-8"))
L = ['within EurekaPlant;',
     'model Parameters "GENERATED by verification/scripts/generate_modelica_inputs.py from configs/parameters.yaml. Do not edit by hand."']
values = {}
for grp, key, name in WANT:
    p = cfg[grp][key]
    unit = UNIT[p["unit"]]
    values[name] = {"value": p["value"], "yaml_unit": p["unit"], "modelica_unit": unit, "provenance": p["provenance"], "yaml_key": f"{grp}.{key}"}
    L.append(f'  parameter Real {name}(unit = "{unit}") = {float(p["value"])!r} "{grp}.{key}; provenance: {p["provenance"]}";')
L.append('  parameter Real SoH(unit = "1") = 1.0 "run property (not in the YAML): battery state of health, constant within a run";')
L.append('end Parameters;')
(pkg / "Parameters.mo").write_text("\n".join(L) + "\n", encoding="ascii")

cfile = root / "configs/cycles/profiles.yaml"
prof = yaml.safe_load(cfile.read_text(encoding="utf-8"))
P = ['within EurekaPlant;',
     'package Profiles "GENERATED from configs/cycles/profiles.yaml: segment lists and a knot builder written in Modelica"']
for nm in ("S1", "S2"):
    segs = prof[nm]["segments"]
    kind, par, tgt = [], [], []
    for sg in segs:
        if "idle" in sg or "cruise" in sg:
            kind.append(1)
            par.append(repr(float(sg.get("idle", sg.get("cruise")))))
            tgt.append("0.0")
        else:
            kind.append(2)
            par.append(repr(float(sg["accel"])))
            tgt.append(f'{float(sg["to_kmh"])!r}/3.6')   # km/h -> m/s written as an expression, evaluated by Modelica
    n = len(segs)
    P.append(f'  constant Integer {nm}_n = {n};')
    P.append(f'  constant Integer {nm}_kind[{nm}_n] = {{{", ".join(map(str, kind))}}} "1 = hold (idle or cruise), 2 = ramp to target";')
    P.append(f'  constant Real {nm}_p[{nm}_n] = {{{", ".join(par)}}} "hold: duration [s]; ramp: acceleration [m/s2]";')
    P.append(f'  constant Real {nm}_target[{nm}_n] = {{{", ".join(tgt)}}} "ramp: target speed [m/s]; hold: unused";')
P.append('''  function knotTimes "Knot times [s] of a piecewise-linear profile"
    input Integer n;
    input Integer kind[n];
    input Real p[n];
    input Real target[n];
    output Real t[n + 1];
  protected
    Real v;
  algorithm
    t[1] := 0.0;
    v := 0.0;
    for i in 1:n loop
      if kind[i] == 1 then
        t[i + 1] := t[i] + p[i];
      else
        t[i + 1] := t[i] + (target[i] - v)/p[i];
        v := target[i];
      end if;
    end for;
  end knotTimes;
  function knotSpeeds "Knot speeds [m/s] of a piecewise-linear profile"
    input Integer n;
    input Integer kind[n];
    input Real p[n];
    input Real target[n];
    output Real v[n + 1];
  algorithm
    v[1] := 0.0;
    for i in 1:n loop
      if kind[i] == 1 then
        v[i + 1] := v[i];
      else
        v[i + 1] := target[i];
      end if;
    end for;
  end knotSpeeds;
end Profiles;''')
(pkg / "Profiles.mo").write_text("\n".join(P) + "\n", encoding="ascii")

meta = {"generator": "verification/scripts/generate_modelica_inputs.py",
        "sources": {"configs/parameters.yaml": sha(pfile), "configs/cycles/profiles.yaml": sha(cfile)},
        "outputs": {"Parameters.mo": sha(pkg / "Parameters.mo"), "Profiles.mo": sha(pkg / "Profiles.mo")},
        "parameters": values, "profiles": {nm: len(prof[nm]["segments"]) for nm in ("S1", "S2")}}
(root / "verification/modelica/generated_inputs.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
print(json.dumps({k: meta[k] for k in ("sources", "outputs", "profiles")}, indent=2))
